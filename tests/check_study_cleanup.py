"""Prevent repeated template skins/controllers returning to migrated modules."""
from pathlib import Path
from bs4 import BeautifulSoup
from study_cleanup import inventory, ROOT

report = inventory(ROOT)
unique = 'CompTIA/A+/1201/Motherboard_and_Connectors/index.html'
required = ['roadmap-theme.css','navigation.css','study-layout.css']
scripts = ['roadmap-theme.js','site-language.js','study-layout.js']
layout_css = (ROOT/'assets/study-layout.css').read_text(encoding='utf8')
for template in ['tabs','core1','articles']:
    assert f'html[data-study-template="{template}"]' in layout_css, template
assert 'data-study-template' not in (ROOT/'assets/roadmap-theme.css').read_text(encoding='utf8'), 'Study template bases belong in the study asset'
assert not report['malformedCSS'], report['malformedCSS']
for row in report['rows']:
    path = ROOT/row['path']
    soup = BeautifulSoup(path.read_text(encoding='utf8'),'html.parser')
    assert row['styleBlocks'] == (1 if row['path'] == unique else 0), row['path']
    assert row['styleAttributes'] == (2 if row['path'] == unique else 0), row['path']
    for name in required:
        assert any((path.parent/href).resolve() == ROOT/'assets'/name for href in row['stylesheets']), (path,name)
    for name in scripts:
        assert any((path.parent/src).resolve() == ROOT/'assets'/name for src in row['scripts']), (path,name)
    template = soup.html.get('data-study-template')
    if row['path'] != unique and 'Linux+' not in row['path']:
        expected = 'core1' if '/1201/' in row['path'] else 'articles' if row['path'].startswith('EC-Council/') else 'tabs'
        assert template == expected, (path, template, expected)
    if template == 'tabs':
        assert not row['inlineScriptHashes'], f'Use the shared tabs controller: {path}'
    # These are generated by the shared enhancer, never copied into each module.
    assert not any(row['structure'][s] for s in ['.study-layout','.study-navigation','.study-helper','.study-meter','.study-toc']), path
print(f"PASS {report['pages']} study modules: required assets, shared skins/chrome/controller, unique content exceptions and valid CSS")
