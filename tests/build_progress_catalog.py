"""Build the small progress inventory from actual assessment and CLI entry points.

Run with --check in regression tests; no question/answer content is exported.
"""
from pathlib import Path
from bs4 import BeautifulSoup
import json, re, sys

ROOT = Path(__file__).resolve().parents[1]

def catalog():
    activities = []
    for path in sorted([*ROOT.glob('CompTIA/**/*.html'), *ROOT.glob('EC-Council/**/*.html')]):
        if path.name.startswith('Old'): continue
        text = path.read_text(encoding='utf8')
        soup = BeautifulSoup(text, 'html.parser')
        if not soup.select_one('#quizForm') or 'quiz-app.js' not in text: continue
        route = path.relative_to(ROOT).as_posix()
        track = 'a' if '/A+/' in route else 'linux' if '/Linux+/' in route else 'security' if '/Security+/' in route else 'ceh'
        title = soup.title.get_text().split(' • ')[0].split(' | ')[0].strip()
        versions = ['1', '2'] if 'FINAL_VERSIONS' in text else ['']
        for version in versions:
            activities.append({'id':route.replace('/index.html', '/')+'?version='+version,
                'url':route+('?version='+version if version else ''), 'type':'assessment', 'track':track,
                'title':title+(' · '+version if version else '')})
    for platform in ['Linux', 'Windows', 'MacOS']:
        path = ROOT/'CLIs'/platform/'index.html'
        text = path.read_text(encoding='utf8')
        data = json.loads(re.search(r'const labData = (.*);', text)[1])
        activities.append({'id':f'CLIs/{platform}/', 'url':f'CLIs/{platform}/index.html',
            'type':'cli', 'track':'clis', 'title':{'Linux':'Linux CLI','Windows':'Windows CLI','MacOS':'macOS CLI'}[platform],
            'steps':[len(s['steps']) for s in data['scenarios']]})
    return '/* Generated by tests/build_progress_catalog.py; stable paths, no learning answers. */\nwindow.ProjectsActivities = '+json.dumps(activities, ensure_ascii=False, indent=2)+';\n'

if __name__ == '__main__':
    target = ROOT/'assets/learning-activities.js'
    expected = catalog()
    if '--check' in sys.argv:
        assert target.read_text(encoding='utf8') == expected, 'Rebuild the progress activity inventory'
        print('PASS progress activity inventory matches repository')
    else:
        target.write_text(expected, encoding='utf8')
